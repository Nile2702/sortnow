import type { MetadataRoute } from "next";

// Without this file, a browser's "Install as app" / "Add to desktop" (what
// shows up to a user as creating a literal desktop/taskbar shortcut "piece
// of software") has no manifest to read icon purpose from, so it falls back
// to generating the shortcut's icon itself - which composites the existing
// transparent app/icon.png onto a white square plate, even though the
// source PNG's background is genuinely transparent. Declaring the icon
// here with purpose "any" (not "maskable", which the PWA spec expects to
// have its own solid-color safe zone a mask can crop into - a plain
// transparent logo isn't designed for that and would still show a
// background plate) tells the installer to use the file's own real
// transparency instead of inventing a backing plate for it.
export default function manifest(): MetadataRoute.Manifest {
  return {
    name: "SORT NOW — Find fashion near you",
    short_name: "SORT NOW",
    description: "Discover apparel from stores near you, sort by what matters, and walk into the store to try it on or buy.",
    start_url: "/",
    display: "standalone",
    background_color: "#f5f5f6",
    theme_color: "#16140f",
    // Chrome's actual installability check (the thing that decides between
    // a "real" installed PWA vs. a plain bookmark shortcut that ignores all
    // of this) wants both a 512x512 AND a 192x192 icon present, not just
    // the one size - both are listed for each purpose below.
    icons: [
      {
        src: "/icon.png",
        sizes: "512x512",
        type: "image/png",
        purpose: "any",
      },
      {
        src: "/icon-192.png",
        sizes: "192x192",
        type: "image/png",
        purpose: "any",
      },
      // Android's home-screen launcher builds an "adaptive icon" from
      // whatever purpose: "maskable" icon it finds, cropping it into a
      // circle/squircle/rounded-square depending on the device's icon
      // shape setting - a maskable icon is expected to fill its own
      // background (the OS doesn't composite one in), so without this,
      // the launcher fell back to a plain white square behind the plain
      // transparent icon above. This is the same logo flattened onto a
      // solid brand-dark fill (public/icon-maskable.png, generated by
      // compositing app/icon.png's own alpha onto #000000, matching the
      // AdminNav/SellerNav bars' background), scaled to 72% of the canvas
      // so it survives every shape mask's safe zone.
      {
        src: "/icon-maskable.png",
        sizes: "512x512",
        type: "image/png",
        purpose: "maskable",
      },
      {
        src: "/icon-maskable-192.png",
        sizes: "192x192",
        type: "image/png",
        purpose: "maskable",
      },
    ],
  };
}
