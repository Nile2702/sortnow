// A status indicator previously rendered with a colored emoji circle
// (🟢🟡🔴⚪⚫) - a plain CSS dot renders at a precise, uniform size/color
// matching the --sio-* token system, where an emoji circle's exact size and
// hue vary by OS/browser and can't be tokenized at all.
export function StatusDot({ color, size = 9 }: { color: string; size?: number }) {
  return <span style={{ display: "inline-block", width: size, height: size, borderRadius: "50%", background: color, flexShrink: 0 }} />;
}
